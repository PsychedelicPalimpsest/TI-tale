import unittest

from tooling.asm_lint import format_text, is_generated, lint_text


class AssemblyLintTests(unittest.TestCase):
    def test_formats_tabs_and_trailing_whitespace(self):
        source = "\tld a, 1  \n"

        self.assertEqual(format_text(source), "    ld a, 1\n")
        self.assertEqual(
            [issue.message for issue in lint_text(source)],
            ["leading indentation must use spaces", "trailing whitespace"],
        )

    def test_indents_macro_and_label_bodies(self):
        source = """MACRO example
ld a, 1
label:
ld b, 2
ENDM
routine:
ret
"""
        expected = """MACRO example
    ld a, 1
label:
    ld b, 2
ENDM
routine:
    ret
"""

        self.assertEqual(format_text(source), expected)

    def test_preserves_a_dedented_macro_code_region(self):
        source = """MACRO example
    PUBLIC symbol
ALIGN 256
label:
    ld a, 1
ENDM
"""

        self.assertEqual(format_text(source), source)

    def test_indents_nested_repetition_and_conditionals(self):
        source = """REPTI value, 1, 2
IF value
db value
ENDIF
ENDR
"""
        expected = """REPTI value, 1, 2
    IF value
        db value
    ENDIF
ENDR
"""

        self.assertEqual(format_text(source), expected)

    def test_preserves_extra_logical_indentation_and_inline_labels(self):
        source = """routine:
        ; logical comment
            ld a, 1
inline:jp (hl)
"""

        self.assertEqual(format_text(source), source)
        self.assertEqual(lint_text(source), [])

    def test_reports_unclosed_explicit_blocks(self):
        issues = lint_text("MACRO example\n    ret\n")

        self.assertEqual(
            [(issue.line, issue.message) for issue in issues],
            [(1, "unclosed macro block")],
        )

    def test_recognizes_generated_files(self):
        self.assertTrue(is_generated("; AUTOGENERATED FILE! Do not edit!\n"))
        self.assertTrue(is_generated("; AUTOGENERATE FILE! Do not edit!\n"))
        self.assertFalse(is_generated("; hand-written assembly\n"))


if __name__ == "__main__":
    unittest.main()
