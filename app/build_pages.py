"""Compile room pages and package a TI-83+ flash application."""

import json
import os
import shlex
import subprocess
from pathlib import Path

import gm_comp


ROOT = Path(__file__).resolve().parent
CRT = "core/custom_ti83papp_crt0.asm"


def run(*args):
    print("$", shlex.join(args), flush=True)
    subprocess.run(args, cwd=ROOT, check=True)


def write_if_changed(path, content):
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main():
    gm_comp._compile(gm_comp.compile_transients())
    gm_comp._compile(gm_comp.compile_rooms())

    pages = {}
    for path in gm_comp.list_rooms():
        room = json.loads(Path(path).read_text())
        page = room.get("page", 0)
        if type(page) is not int or page < 0 or page > 255:
            raise ValueError(f"{path}: page must be between 0 and 255")
        pages.setdefault(page, []).append((path, room))
    if not pages or sorted(pages) != list(range(len(pages))):
        raise ValueError("room pages must be contiguous, starting at page 0")

    cflags = shlex.split(os.environ.get("CFLAGS", ""))
    binaries = []
    for page, rooms in sorted(pages.items()):
        source = ROOT / f"page_{page}.c"
        declarations = [f"extern void ROOM_init_{room['id']}(void);" for _, room in rooms]
        if page == 0:
            body = ["void init_first_room(void) {", f"    ROOM_init_{rooms[0][1]['id']}();", "}"]
        else:
            body = [f"void page_entry_{page}(void) {{"]
            body += [f"    ROOM_init_{room['id']}();" for _, room in rooms]
            body += ["}"]
        write_if_changed(source, "// AUTOGENERATED FILE! Do not edit!\n" +
                         "\n".join(declarations + body) + "\n")

        objects = set()
        sprites = set()
        for _, room in rooms:
            for instance in room.get("instances", []):
                oid = instance["object"]
                objects.add(oid)
                object_json = json.loads((ROOT / "game/objects" / f"{oid}.json").read_text())
                if object_json.get("sprite"):
                    sprites.add(object_json["sprite"])
        deps = [str(Path(path).with_suffix(".o")) for path, _ in rooms]
        deps += [f"game/objects/{oid}.o" for oid in sorted(objects)]
        deps += [f"game/sprites/{sid}.o" for sid in sorted(sprites)]
        output = "out" if page == 0 else f"page_{page}"
        source_files = (["first_page.c"] if page == 0 else []) + [source.name]
        multipage_flags = ["-pragma-define:MULTI_PAGE_CALLS=1"] if len(pages) > 1 and page == 0 else []
        run("zcc", "+ti83p", "-L.", "-lcore", "-lengine_resident",
            "-lengine_page", "-o", output, *source_files, *deps,
            f"-crt0={CRT}", f"-startup={0 if page == 0 else 9}",
            *multipage_flags, *cflags)
        binary = ROOT / f"{output}_CODE.bin"
        if binary.stat().st_size > 16384:
            raise ValueError(f"page {page} is larger than 16 KiB")
        binaries.append(output)

    if len(binaries) == 1:
        run("z88dk-appmake", "+ti83papp", "--single-page", "--binfile", "out",
            "--crt0file", CRT, "--output", "out.8xk")
    else:
        run("z88dk-appmake", "+ti83papp", "--combine-pages", "--binfile", "out",
            "--other-pages", ",".join(binaries), "--crt0file", CRT,
            "--output", "out.8xk")
    if not (ROOT / "out.map").stat().st_size:
        raise ValueError("first page linker map is empty")


if __name__ == "__main__":
    main()
